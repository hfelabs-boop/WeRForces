export const DEFAULT_CATALOG: Catalog = { entityTypes, weapons, sensors, unitTemplates };

/**
 * Merge a catalog extension into a base catalog: entries whose id already exists are
 * replaced, new ids are appended. Used by `--catalog <file.json>`.
 */
export function mergeCatalog(base: Catalog, ext: Partial<Catalog>): Catalog {
  const merge = <T extends { id: string }>(a: T[], b: T[] | undefined): T[] => {
    if (!b) return a;
    if (!Array.isArray(b)) throw new Error('catalog extension sections must be arrays');
    const out = a.filter((x) => !b.some((y) => y.id === x.id));
    return [...out, ...b];
  };
  return {
    entityTypes: merge(base.entityTypes, ext.entityTypes),
    weapons: merge(base.weapons, ext.weapons),
    sensors: merge(base.sensors, ext.sensors),
    unitTemplates: merge(base.unitTemplates, ext.unitTemplates),
  };
}

/** Indexed view over a catalog for fast lookups. */
export class CatalogIndex {
  readonly types = new Map<string, EntityTypeDef>();
  readonly weapons = new Map<string, WeaponDef>();
  readonly sensors = new Map<string, SensorDef>();
  readonly templates = new Map<string, UnitTemplate>();

  constructor(readonly catalog: Catalog = DEFAULT_CATALOG) {
    for (const t of catalog.entityTypes) this.types.set(t.id, t);
    for (const w of catalog.weapons) this.weapons.set(w.id, w);
    for (const s of catalog.sensors) this.sensors.set(s.id, s);
    for (const u of catalog.unitTemplates) this.templates.set(u.id, u);
    for (const t of catalog.entityTypes) {
      for (const w of t.weapons) if (!this.weapons.has(w)) throw new Error(`entity type ${t.id} references unknown weapon ${w}`);
      for (const s of t.sensors) if (!this.sensors.has(s)) throw new Error(`entity type ${t.id} references unknown sensor ${s}`);
    }
    for (const u of catalog.unitTemplates) {
      for (const m of u.members) if (!this.types.has(m)) throw new Error(`unit template ${u.id} references unknown type ${m}`);
    }
  }

  type(id: string): EntityTypeDef {
    const t = this.types.get(id);
    if (!t) throw new Error(`unknown entity type: ${id}`);
    return t;
  }

  weapon(id: string): WeaponDef {
    const w = this.weapons.get(id);
    if (!w) throw new Error(`unknown weapon: ${id}`);
    return w;
  }

  /** Best catalog match for a DIS entity type received from the network. */
  matchDisType(t: DisEntityType): EntityTypeDef {
    let best: EntityTypeDef | undefined;
    let bestScore = -1;
    for (const def of this.catalog.entityTypes) {
      const d = def.dis;
      if (d.kind !== t.kind || d.domain !== t.domain) continue;
      let score = 1;
      if (d.country === t.country) score += 4;
      if (d.category === t.category) {
        score += 8;
        if (d.subcategory === t.subcategory) {
          score += 2;
          if (d.specific === t.specific) score += 1;
        }
      }
      if (score > bestScore) {
        bestScore = score;
        best = def;
      }
    }
    if (best) return best;
    // Fall back to any type of the same DIS domain, then to the first type.
    const domainMap: Record<number, string> = { 1: 'ground', 2: 'air', 3: 'surface' };
    const wanted = t.kind === 3 ? 'lifeform' : domainMap[t.domain];
    return this.catalog.entityTypes.find((d) => d.domain === wanted) ?? this.catalog.entityTypes[0];
  }
}
