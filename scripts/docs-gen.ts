// Generates the reference pages that are derived from code, so they cannot drift:
//   docs/reference/catalog.md   (entity types, weapons, sensors, unit templates)
//   docs/reference/mcp-tools.md (MCP tools and their parameters)
// Run with: npm run docs:gen   (test/docs.test.ts fails when they are out of date)

import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createMcpServer, SERVER_INSTRUCTIONS } from '../src/mcp/tools.js';
import { DEFAULT_CATALOG } from '../src/sim/catalog.js';
import type { DisEntityType } from '../src/shared/types.js';

const GENERATED = '<!-- Generated by scripts/docs-gen.ts — edit the code, then run `npm run docs:gen`. -->';

const dis = (d: DisEntityType) => [d.kind, d.domain, d.country, d.category, d.subcategory, d.specific, d.extra].join('.');
const kmh = (ms: number) => Math.round(ms * 3.6);
const deg = (rad: number) => Math.round((rad * 180) / Math.PI);
const esc = (s: string) => s.replace(/\|/g, '\\|');

export function catalogMarkdown(): string {
  const c = DEFAULT_CATALOG;
  const weapon = (id: string) => c.weapons.find((w) => w.id === id)!;
  const sensor = (id: string) => c.sensors.find((s) => s.id === id)!;
  const type = (id: string) => c.entityTypes.find((t) => t.id === id)!;
  const lines: string[] = [GENERATED, '', '# Catalog reference', ''];
  lines.push(
    'The default simulation object model (`src/sim/catalog.ts`). Ids are what you pass as `typeId` / `templateId` in the GUI, REST API and MCP tools. To add your own types see [Tutorial 9](../tutorials/09-extending-the-catalog.md).',
    '',
    'DIS enumerations are representative values in the SISO-REF-010 layout (kind.domain.country.category.subcategory.specific.extra; country 225 = USA, 222 = Russia).',
    '',
  );

  lines.push('## Entity types', '');
  for (const domain of ['ground', 'lifeform', 'air', 'surface'] as const) {
    const title = { ground: 'Ground vehicles', lifeform: 'Dismounted', air: 'Aircraft', surface: 'Surface vessels' }[domain];
    lines.push(`### ${title}`, '');
    lines.push('| Id | Name | Max / cruise speed | Armour class | Weapons | Sensors | DIS type |', '| --- | --- | --- | --- | --- | --- | --- |');
    for (const t of c.entityTypes.filter((x) => x.domain === domain)) {
      const speed = `${kmh(t.maxSpeed)} / ${kmh(t.cruiseSpeed)} km/h${t.cruiseAltitude ? `, ${t.cruiseAltitude} m AGL` : ''}`;
      lines.push(
        `| \`${t.id}\` | ${esc(t.name)} — ${esc(t.description)} | ${speed} | ${t.armor} | ${t.weapons.map((w) => weapon(w).name).join('<br>') || '—'} | ${t.sensors.map((s) => sensor(s).name).join('<br>') || '—'} | ${dis(t.dis)} |`,
      );
    }
    lines.push('');
  }

  lines.push('## Weapons', '', 'Pk is the probability of a catastrophic kill per shot at short range against each armour class, before range, motion and concealment modifiers (see [Concepts](../concepts.md#combat-and-damage)).', '');
  lines.push('| Id | Name | Range | Reload | Ammo | Guided | Engages | Pk by target class |', '| --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const w of c.weapons) {
    const pk = Object.entries(w.pk)
      .map(([k, v]) => `${k} ${v}`)
      .join(', ');
    lines.push(`| \`${w.id}\` | ${esc(w.name)} | ${w.minRange}–${w.maxRange} m | ${w.reloadTime} s | ${w.ammo} | ${w.guided ? 'yes' : 'no'} | ${w.targets.join(', ')} | ${pk} |`);
  }
  lines.push('');

  lines.push('## Sensors', '');
  lines.push('| Id | Name | Range | Field of view | Detects | Radar |', '| --- | --- | --- | --- | --- | --- |');
  for (const s of c.sensors) {
    lines.push(`| \`${s.id}\` | ${esc(s.name)} | ${s.maxRange} m | ${deg(s.fov)}° | ${s.detects.join(', ')} | ${s.radar ? 'yes' : 'no'} |`);
  }
  lines.push('');

  lines.push('## Unit templates', '');
  lines.push('| Id | Name | Echelon | Members | Formation | Spacing |', '| --- | --- | --- | --- | --- | --- |');
  for (const u of c.unitTemplates) {
    const counts = new Map<string, number>();
    for (const m of u.members) counts.set(m, (counts.get(m) ?? 0) + 1);
    const members = [...counts].map(([id, n]) => `${n}× ${type(id).name}`).join(', ');
    lines.push(`| \`${u.id}\` | ${esc(u.name)} | ${u.echelon} | ${members} | ${u.formation} | ${u.spacing} m |`);
  }
  lines.push('');
  return lines.join('\n');
}

interface JsonSchema {
  type?: string | string[];
  description?: string;
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  items?: JsonSchema;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  minimum?: number;
  maximum?: number;
}

function schemaType(s: JsonSchema): string {
  if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' \\| ');
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.anyOf) return s.anyOf.map(schemaType).join(' or ');
  if (s.type === 'array') return `array of ${s.items ? schemaType(s.items) : 'any'}`;
  if (s.type === 'object' && s.properties) return `{${Object.keys(s.properties).join(', ')}}`;
  const t = Array.isArray(s.type) ? s.type.join('/') : (s.type ?? 'any');
  const range = s.minimum !== undefined || s.maximum !== undefined ? ` (${s.minimum ?? ''}–${s.maximum ?? ''})` : '';
  return `${t}${range}`;
}

export async function mcpToolsMarkdown(): Promise<string> {
  const server = createMcpServer(async () => ({ status: 200, json: {} }));
  const [a, b] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'docs-gen', version: '1.0.0' });
  await Promise.all([server.connect(a), client.connect(b)]);
  const { tools } = await client.listTools();
  const { resources } = await client.listResources();
  await client.close();

  const lines: string[] = [GENERATED, '', '# MCP tools reference', ''];
  lines.push(
    'Tools exposed by the WeRForces MCP server (`/mcp` or `dist/mcp/stdio.js`). See [Tutorial 5](../tutorials/05-ai-agents-with-mcp.md) for setup.',
    '',
    'Instructions sent to the client when it connects:',
    '',
    ...SERVER_INSTRUCTIONS.split('\n').map((l) => `> ${l}`),
    '',
  );
  for (const t of tools) {
    const hints = [t.annotations?.readOnlyHint && 'read-only', t.annotations?.destructiveHint && 'destructive', t.annotations?.idempotentHint && 'idempotent'].filter(Boolean);
    lines.push(`## \`${t.name}\`${hints.length ? ` _(${hints.join(', ')})_` : ''}`, '', t.description ?? '', '');
    const schema = t.inputSchema as JsonSchema;
    const props = Object.entries(schema.properties ?? {});
    if (props.length === 0) {
      lines.push('No parameters.', '');
      continue;
    }
    lines.push('| Parameter | Type | Required | Description |', '| --- | --- | --- | --- |');
    for (const [name, p] of props) {
      lines.push(`| \`${name}\` | ${schemaType(p)} | ${schema.required?.includes(name) ? 'yes' : ''} | ${esc(p.description ?? '')} |`);
    }
    lines.push('');
  }
  lines.push('## Resources', '', '| URI | Description |', '| --- | --- |');
  for (const r of resources) lines.push(`| \`${r.uri}\` | ${esc(r.description ?? '')} |`);
  lines.push('');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync('docs/reference/catalog.md', catalogMarkdown());
  writeFileSync('docs/reference/mcp-tools.md', await mcpToolsMarkdown());
  console.log('wrote docs/reference/catalog.md and docs/reference/mcp-tools.md');
}
